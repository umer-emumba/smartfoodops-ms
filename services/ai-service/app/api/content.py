"""Restaurant content (docs/week5-plan.md step 5) — for a restaurant's
owner only:

    POST /v1/ai/content                 ask for a draft → 202, generated by ai-worker
    GET  /v1/ai/content?restaurant_id=  the restaurant's drafts, newest first
    GET  /v1/ai/content/{id}            one draft (poll until ready / failed)
    POST /v1/ai/content/{id}/accept     apply it (description, promotion) or keep it
    POST /v1/ai/content/{id}/reject

Nothing reaches the catalog without an accept (B5-D7); accepting goes
through restaurant-service with the owner's own token, so its rules decide."""

from collections.abc import Callable
from typing import Any, Literal

from fastapi import APIRouter, Depends, Query, Request, status
from pydantic import BaseModel, ConfigDict, Field, model_validator
from sfo_auth import CurrentUser, Role
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from app.api.chat import _token, get_sessions
from app.auth_deps import require_roles
from app.celery_app import enqueue_content
from app.content import service

router = APIRouter(prefix="/v1/ai/content", tags=["ai-content"])

OWNER = Depends(require_roles(Role.RESTAURANT_ADMIN))
Kind = Literal[
    "menu_description", "promotion", "dish_picks", "engagement_message", "feedback_summary"
]
Note = Field(default=None, max_length=300)


class ContentRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    restaurant_id: str = Field(max_length=64)
    kind: Kind
    menu_item_id: str | None = Field(default=None, max_length=64, description="menu_description")
    notes: str | None = Note  # menu_description: anything to bring out
    goal: str | None = Note  # promotion / dish_picks: what the owner wants from it
    about: str | None = Note  # engagement_message: what the message is about
    tone: Literal["friendly", "formal", "playful"] | None = None

    @model_validator(mode="after")
    def _needs(self) -> "ContentRequest":
        if self.kind == "menu_description" and not self.menu_item_id:
            raise ValueError("menu_description needs menu_item_id")
        return self

    def params(self) -> dict[str, Any]:
        return self.model_dump(exclude={"restaurant_id", "kind"}, exclude_none=True)


def get_enqueue() -> Callable[[str], None]:
    return enqueue_content


@router.post("", status_code=status.HTTP_202_ACCEPTED)
async def request_content(
    body: ContentRequest,
    current: CurrentUser = OWNER,
    sessions: async_sessionmaker[AsyncSession] = Depends(get_sessions),
    enqueue: Callable[[str], None] = Depends(get_enqueue),
) -> dict[str, Any]:
    await service.ensure_owner(body.restaurant_id, current.id)
    draft = await service.create(
        sessions,
        restaurant_id=body.restaurant_id,
        user_id=current.id,
        kind=body.kind,
        params=body.params(),
        enqueue=enqueue,
    )
    return service.view(draft)


@router.get("")
async def list_content(
    restaurant_id: str = Query(max_length=64),
    current: CurrentUser = OWNER,
    sessions: async_sessionmaker[AsyncSession] = Depends(get_sessions),
) -> dict[str, Any]:
    await service.ensure_owner(restaurant_id, current.id)
    return {"items": [service.view(d) for d in await service.list_owned(sessions, restaurant_id)]}


@router.get("/{draft_id}")
async def get_content(
    draft_id: str,
    current: CurrentUser = OWNER,
    sessions: async_sessionmaker[AsyncSession] = Depends(get_sessions),
) -> dict[str, Any]:
    return service.view(await service.get_owned(sessions, draft_id, current.id))


@router.post("/{draft_id}/accept")
async def accept_content(
    draft_id: str,
    request: Request,
    current: CurrentUser = OWNER,
    sessions: async_sessionmaker[AsyncSession] = Depends(get_sessions),
) -> dict[str, Any]:
    draft = await service.get_owned(sessions, draft_id, current.id)
    return service.view(await service.accept(sessions, draft, _token(request)))


@router.post("/{draft_id}/reject")
async def reject_content(
    draft_id: str,
    current: CurrentUser = OWNER,
    sessions: async_sessionmaker[AsyncSession] = Depends(get_sessions),
) -> dict[str, Any]:
    draft = await service.get_owned(sessions, draft_id, current.id)
    return service.view(await service.reject(sessions, draft))
