import re
from typing import Literal

from pydantic import SecretStr
from sfo_common import BaseServiceSettings
from sfo_common.config import CelerySettings, KafkaConsumerSettings


class Settings(BaseServiceSettings, KafkaConsumerSettings, CelerySettings):
    # Vector store (docs/week4-plan.md B4-D2). Short timeout: a Qdrant outage
    # fails a search or readiness check fast instead of hanging the request.
    qdrant_url: str = "http://qdrant:6333"
    qdrant_timeout_seconds: int = 5

    # Embeddings (B4-D3): fastembed, local ONNX models. The image downloads
    # them at build time into this directory (Dockerfile); empty means
    # fastembed's default cache, for running outside Docker. bge-base won the
    # model comparison (B4-D18, scripts/compare_models.sh) over bge-small.
    dense_model: str = "BAAI/bge-base-en-v1.5"
    dense_dim: int = 768
    # BGE's recommended instruction for short search queries (not for the
    # documents). Empty turns it off — step 5's retrieval eval compares both.
    dense_query_prefix: str = "Represent this sentence for searching relevant passages: "
    # Some models also want one in front of each document (embeddinggemma's
    # "title: none | text: "); BGE doesn't. Dense only — BM25 and the stored
    # text never see either prefix. Set by scripts/compare_models.sh (B4-D18).
    dense_document_prefix: str = ""
    sparse_model: str = "Qdrant/bm25"
    # Weighted RRF (app/retrieval.py): how much each list counts in the
    # fused ranking. Equal weights make "1st by one, 2nd by the other" an
    # exact tie, ordered arbitrarily between runs. On the golden set
    # (scripts/eval_retrieval.py) weights and the query prefix moved scores by
    # at most one query; dense 1.2 ties for best and makes the order stable.
    fusion_dense_weight: float = 1.2
    fusion_sparse_weight: float = 1.0
    # RRF's k: each list gives a result weight / (k + rank). Small k lets one
    # list's top places dominate; large k (60 in the RRF paper) rewards being
    # in both lists. 2 is Qdrant's own default.
    fusion_k: int = 2
    embedding_cache_dir: str = ""
    # ONNX threads per model. Embedding runs off the event loop
    # (app/embedding.py), one batch at a time.
    embedding_threads: int = 2
    # Bump when the documents' text or payload changes shape: with the dense
    # model it names the collections (B4-D6), so a new index is built next to
    # the old one by `python -m app.reindex` instead of mixing two formats.
    # r2 (Week 5 step 1): `cuisine_words` and `words` in the payload.
    index_revision: int = 2

    # The customer summary (app/documents.py) is built from this many of the
    # latest orders: recent taste, and a rebuild that costs the same however
    # long the history grows.
    summary_max_orders: int = 50

    # Where the backfill reads from (app/reindex.py) — internal endpoints.
    restaurant_service_url: str = "http://restaurant-service:8000"
    order_service_url: str = "http://order-service:8000"
    # Order explanations read these public APIs as the customer (step 4).
    delivery_service_url: str = "http://delivery-service:8000"
    payment_service_url: str = "http://payment-service:8000"
    order_facts_timeout_seconds: float = 3.0
    # Times in explanations are shown in Pakistan time (no daylight saving).
    display_utc_offset_hours: float = 5.0

    # Restaurant content (step 5), generated by ai-worker (Celery).
    # Feedback summaries read up to this many of the newest reviews, in
    # batches: each batch summarised, then the batches combined.
    content_max_reviews: int = 200
    content_review_batch: int = 25
    # A draft still pending this long is queued again (the API commits, then
    # enqueues; a crash or broker outage in between would strand it).
    content_sweep_after_seconds: int = 120
    content_sweep_interval_seconds: int = 60
    content_max_attempts: int = 3
    # Restaurant suggestions read kitchen load live (app/restaurant_client.py); past
    # this they rank without it rather than wait.
    kitchen_load_timeout_seconds: float = 1.0

    # The LLM (docs/week5-plan.md B5-D1). Only app/llm.py reads these. Which
    # provider, and its key: empty until the user adds one to .env (the
    # assistant then answers in degraded mode); SecretStr keeps it out of logs.
    llm_provider: Literal["anthropic", "openai"] = "anthropic"
    llm_api_key: SecretStr = SecretStr("")
    # For OpenAI-compatible endpoints (Azure OpenAI, vLLM, Ollama). Empty means
    # the provider's own API.
    llm_base_url: str = ""
    # Models by role: "smart" writes answers, "fast" does the cheap steps
    # (intent, constraints, rewriting). Empty means the provider's default in
    # app/llm.py — OpenAI has none there, so it must be set.
    llm_model_smart: str = ""
    llm_model_fast: str = ""
    # Reasoning effort per role (low | medium | high …). Empty means the
    # default in app/llm.py; "omit" means not sent (models that reject it).
    # "none" is sent as is: it turns thinking off on models that think by
    # default (qwen3 on Ollama: 13 s → 2.8 s a call, same answer).
    llm_effort_smart: str = ""
    llm_effort_fast: str = ""
    # Output caps per call (B5-D10). Thinking counts against them, so they
    # leave room for it; the per-step limits are tightened from measurements.
    llm_max_tokens_smart: int = 4096
    llm_max_tokens_fast: int = 2048
    # Per attempt; the provider SDK retries 429/5xx/connection errors itself
    # with backoff, so a call can take up to timeout x (retries + 1).
    llm_timeout_seconds: float = 30.0
    llm_max_retries: int = 2
    # A smart-model call that fails for a transient reason (rate limit,
    # outage, timeout) is retried once on the fast model.
    llm_fallback_to_fast: bool = True

    # The assistant (docs/week5-plan.md step 2).
    # Prices are PKR; a budget in dollars is converted at this fixed rate and
    # the answer says so (there's no live FX feed).
    usd_to_pkr: float = 280.0
    # Dishes retrieved for the pick step: enough choice, a bounded prompt.
    assistant_candidates: int = 15
    assistant_restaurants: int = 5
    # Search radius around the customer, when the request carries a location.
    assistant_radius_km: float = 8.0
    # Memory: the last N turns go to the model word for word; older ones are
    # folded into the conversation summary once this many are unsummarized.
    assistant_history_turns: int = 6
    assistant_summarize_after: int = 12
    # Longest customer message accepted.
    assistant_max_message_chars: int = 500
    # A conversation is busy while a turn is answered (409 for a second
    # message); the mark expires after this long if the process dies. Longer
    # than a slow turn (~65 s on a local 8B model).
    assistant_turn_lock_seconds: int = 120
    # SSE comment sent while a turn has nothing new to say: the gateway closes
    # an AI stream after 45 s of silence (B5-D13), i.e. 3 missed heartbeats.
    assistant_heartbeat_seconds: float = 15.0

    @property
    def index_suffix(self) -> str:
        """`bge_base_en_v1_5_r1`: the dense model and document revision."""
        model = re.sub(r"[^a-z0-9]+", "_", self.dense_model.rsplit("/", 1)[-1].lower())
        return f"{model}_r{self.index_revision}"


settings = Settings()  # type: ignore[call-arg]
